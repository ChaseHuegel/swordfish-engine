    private static string BuildEntitySystemClass(int n, bool refQuery)
    {
        var writer = new CodeWriter();
        string className = refQuery ? $"EntitySystemRef{AngleTypeParams(n)}" : $"EntitySystem{AngleTypeParams(n)}";
        string baseDelegate = refQuery ? $"ForEachRef{AngleTypeParams(n)}" : $"ForEach{AngleTypeParams(n)}";
        string queryName = refQuery ? "QueryRef" : "Query";
        string onTickParams = refQuery ? RefRefCompParams(n) : RefCompParams(n);
        string ctorName = refQuery ? "EntitySystemRef" : "EntitySystem";

        writer.Line($"public abstract class {className} : IEntitySystem");
        EmitConstraints(writer, n);
        writer.EnterBlock();
        writer.Line($"private readonly {baseDelegate} _onTick;");
        writer.BlankLine();
        writer.Line($"protected {ctorName}()");
        writer.EnterBlock();
        writer.Line("_onTick = OnTick;");
        writer.ExitBlock();
        writer.BlankLine();
        writer.Line("public void Tick(float delta, DataStore store)");
        writer.EnterBlock();
        writer.Line($"store.{queryName}{AngleTypeParams(n)}(delta, _onTick);");
        writer.ExitBlock();
        writer.BlankLine();
        writer.Line($"protected abstract void OnTick(float delta, DataStore store, int entity, {onTickParams});");
        writer.ExitBlock();
        return writer.ToString();
    }

    private static string BuildEntitySystem()
    {
        var writer = new CodeWriter();
        writer.Raw(Header);
        writer.BlankLine();
        for (var n = 1; n <= MaxComponents; n++)
        {
            writer.Raw(BuildEntitySystemClass(n, refQuery: false));
            writer.BlankLine();
            writer.Raw(BuildEntitySystemClass(n, refQuery: true));
            writer.BlankLine();
        }

        return writer.ToString();
    }
