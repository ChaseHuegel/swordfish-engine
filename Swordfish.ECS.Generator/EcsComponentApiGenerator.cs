        writer.Line("public readonly partial struct Entity");
        writer.EnterBlock();
        for (var n = 1; n <= MaxComponents; n++)
        {
            EmitEntityMethods(writer, n);
            writer.BlankLine();
        }

        writer.ExitBlock();
        return writer.ToString();
    }

