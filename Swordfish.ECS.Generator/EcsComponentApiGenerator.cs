    private static void EmitEntityMethods(CodeWriter writer, int n)
    {
        EmitMethod(writer, "Add", TypeParams(n), "", n, null, "bool");
        writer.Line($"if (Has{AngleTypeParams(n)}())");
        writer.EnterBlock();
        writer.Line("return false;");
        writer.ExitBlock();
        writer.BlankLine();
        writer.Line($"_dataStore.AddOrUpdate(Ptr, {DefaultArgs(n)});");
        writer.Line("return true;");
        writer.ExitBlock();

        EmitMethod(writer, "AddOrUpdate", TypeParams(n), CompParams(n), n, null);
        writer.Line($"_dataStore.AddOrUpdate(Ptr, {CompArgs(n)});");
        writer.ExitBlock();

        EmitMethod(writer, "Remove", TypeParams(n), "", n, null, "bool");
        writer.Line($"return _dataStore.Remove{AngleTypeParams(n)}(Ptr);");
        writer.ExitBlock();

        EmitMethod(writer, "Has", TypeParams(n), "", n, null, "bool");
        writer.Line($"return _dataStore.TryGet{AngleTypeParams(n)}(Ptr, {Discards(n)});");
        writer.ExitBlock();

        EmitMethod(writer, "TryGet", TypeParams(n), OutDecls(n), n, null, "bool");
        writer.Line($"return _dataStore.TryGet{AngleTypeParams(n)}(Ptr, {OutArgs(n)});");
        writer.ExitBlock();
    }

    private static string BuildEntity()
    {
        var writer = new CodeWriter();
        writer.Raw(Header);
