using System;
using System.Collections.Generic;
using System.Globalization;
using System.Numerics;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Reef.Generator;

/// <summary>Emits the token constants declared by a palette document.</summary>
internal static class PaletteEmitter
{
    public static string? Emit(
        RmlDocument document,
        StyleCatalog styleCatalog,
        string className,
        string namespaceName,
        List<Diagnostic> diagnostics)
    {
        string prefix = document.Palette!.Trim();
        if (!IsValidPrefix(prefix))
        {
            diagnostics.Add(Diagnostic.Create(
                DiagnosticDescriptors.InvalidPalette,
                document.ClassLocation,
                "Token prefix '" + prefix + "' is not a lower-case identifier."));
            return null;
        }

        if (document.Roots.Count > 0)
        {
            diagnostics.Add(Diagnostic.Create(
                DiagnosticDescriptors.InvalidPalette,
                document.ClassLocation,
                "A palette document must not declare elements."));
            return null;
        }

        string memberPrefix = prefix + "-";
        var members = new List<PaletteMember>();
        var memberNames = new HashSet<string>(StringComparer.Ordinal);

        foreach (KeyValuePair<string, List<RssToken>> variable in styleCatalog.Variables)
        {
            if (!variable.Key.StartsWith(memberPrefix, StringComparison.Ordinal))
            {
                continue;
            }

            string memberName = ToPascalCase(variable.Key.Substring(memberPrefix.Length));
            if (memberName.Length == 0)
            {
                continue;
            }

            styleCatalog.TryGetVariableLocation(variable.Key, out Location location);
            if (!memberNames.Add(memberName))
            {
                diagnostics.Add(Diagnostic.Create(
                    DiagnosticDescriptors.InvalidPalette,
                    location,
                    "Token '--" + variable.Key + "' maps to a member name already in use, '" + memberName + "'."));
                continue;
            }

            if (!TryReadValue(variable.Value, out string typeName, out string valueCode, out string error))
            {
                diagnostics.Add(Diagnostic.Create(
                    DiagnosticDescriptors.InvalidPalette,
                    location,
                    "Token '--" + variable.Key + "' " + error));
                continue;
            }

            members.Add(new PaletteMember(variable.Key, memberName, typeName, valueCode));
        }

        members.Sort((left, right) => string.CompareOrdinal(left.Token, right.Token));

        string access = string.Equals(document.Access, "public", StringComparison.OrdinalIgnoreCase)
            ? "public"
            : "internal";

        var writer = new CodeWriter();
        writer.Line("// <auto-generated by Reef.Generator />");
        writer.Line("#nullable enable");
        writer.Line();
        if (namespaceName.Length > 0)
        {
            writer.Line("namespace " + namespaceName + ";");
            writer.Line();
        }

        writer.Line("/// <summary>The theme token constants declared by the stylesheets.</summary>");
        writer.Line(access + " static class " + className);
        writer.Open();
        for (var i = 0; i < members.Count; i++)
        {
            PaletteMember member = members[i];
            if (i > 0)
            {
                writer.Line();
            }

            writer.Line("/// <summary>Token <c>--" + member.Token + "</c>.</summary>");
            writer.Line("public static readonly " + member.TypeName + " " + member.Name + " = " + member.ValueCode + ";");
        }

        writer.Close();
        return writer.ToString();
    }

    private static bool TryReadValue(
        List<RssToken> tokens,
        out string typeName,
        out string valueCode,
        out string error)
    {
        typeName = "int";
        valueCode = "0";
        error = string.Empty;

        var values = new List<RssToken>();
        for (var i = 0; i < tokens.Count; i++)
        {
            if (!tokens[i].IsTrivia)
            {
                values.Add(tokens[i]);
            }
        }

        if (values.Count == 1 && values[0].Kind == RssTokenKind.String)
        {
            typeName = "string";
            valueCode = FnvHash.EscapeString(values[0].Text);
            return true;
        }

        if (values.Count == 1 && values[0].Kind == RssTokenKind.Number)
        {
            string text = values[0].Text;
            if (text.EndsWith("px", StringComparison.OrdinalIgnoreCase))
            {
                text = text.Substring(0, text.Length - 2);
            }

            if (int.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out int number))
            {
                typeName = "int";
                valueCode = number.ToString(CultureInfo.InvariantCulture);
                return true;
            }

            error = "must be an integer, a quoted string, or a colour.";
            return false;
        }

        if (ColorParser.TryParse(values, out Vector4 color, out _))
        {
            typeName = "global::System.Numerics.Vector4";
            valueCode = FnvHash.FormatVector(color);
            return true;
        }

        error = "must be an integer, a quoted string, or a colour.";
        return false;
    }

    private static bool IsValidPrefix(string prefix)
    {
        if (prefix.Length == 0 || !char.IsLower(prefix[0]))
        {
            return false;
        }

        for (var i = 1; i < prefix.Length; i++)
        {
            if (!char.IsLower(prefix[i]) && !char.IsDigit(prefix[i]) && prefix[i] != '-')
            {
                return false;
            }
        }

        return true;
    }

    private static string ToPascalCase(string name)
    {
        var builder = new StringBuilder(name.Length);
        var upper = true;
        for (var i = 0; i < name.Length; i++)
        {
            char c = name[i];
            if (c == '-')
            {
                upper = true;
                continue;
            }

            builder.Append(upper ? char.ToUpperInvariant(c) : c);
            upper = false;
        }

        return builder.ToString();
    }

    private readonly struct PaletteMember
    {
        public readonly string Token;
        public readonly string Name;
        public readonly string TypeName;
        public readonly string ValueCode;

        public PaletteMember(string token, string name, string typeName, string valueCode)
        {
            Token = token;
            Name = name;
            TypeName = typeName;
            ValueCode = valueCode;
        }
    }
}
